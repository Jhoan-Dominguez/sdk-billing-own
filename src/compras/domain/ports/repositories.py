"""Persistencia: repositorios por agregado y una unidad de trabajo que los agrupa.

Convención de acceso: las consultas que devuelven datos de usuarios reciben
`owner_id`; None significa "todos" y solo debe venir de `Viewer.owner_filter()`.
"""

from collections.abc import Iterable
from datetime import date
from typing import Protocol, Self

from compras.domain.models import Attachment, Category, Purchase, User


class UserRepository(Protocol):
    def get(self, user_id: str) -> User | None: ...
    def add(self, user: User) -> None: ...
    def delete(self, user: User) -> None: ...
    def list(self, role: str | None = None) -> list[User]: ...
    def replace_default_category(self, old: str, new: str | None, *, owner_id: str | None) -> None:
        """Cambia la categoría por defecto `old` por `new` (de `owner_id` o de todos)."""
        ...


class PurchaseRepository(Protocol):
    def get(self, purchase_id: int) -> Purchase | None: ...
    def add(self, purchase: Purchase) -> None: ...
    def delete(self, purchase: Purchase) -> None: ...
    def between(self, start: date, end: date, *, owner_id: str | None) -> list[Purchase]:
        """Compras con fecha en [start, end), de la más reciente a la más antigua."""
        ...

    def by_owner(self, owner_id: str) -> list[Purchase]: ...
    def count_by_category(self, *, owner_id: str | None) -> dict[str, int]: ...
    def reassign_category(
        self, old: str, new: str, *, owner_id: str | None, exclude_owner_ids: Iterable[str] = ()
    ) -> int:
        """Cambia la categoría `old` por `new` y devuelve cuántas compras cambió."""
        ...


class AttachmentRepository(Protocol):
    def get(self, attachment_id: int) -> Attachment | None: ...
    def add(self, attachment: Attachment) -> None: ...
    def delete(self, attachment: Attachment) -> None: ...
    def drafts(self, *, owner_id: str | None) -> list[Attachment]:
        """Adjuntos sin compra (borradores), los más recientes primero."""
        ...

    def same_content(self, sha256: str, *, owner_id: str, exclude_id: int) -> list[Attachment]: ...


class CategoryRepository(Protocol):
    def get(self, category_id: int) -> Category | None: ...
    def add(self, category: Category) -> None: ...
    def delete(self, category: Category) -> None: ...
    def visible_to(self, owner_id: str | None) -> list[Category]:
        """Generales + personales de `owner_id` (None = solo generales)."""
        ...

    def find_name(self, name: str, *, owner_id: str | None, exclude_id: int | None = None) -> Category | None:
        """Una categoría general o de `owner_id` con ese nombre (sin distinguir mayúsculas)."""
        ...

    def owners_with_personal(self, name: str) -> list[str]:
        """Usuarios con una categoría personal llamada `name`."""
        ...


class UnitOfWork(Protocol):
    """Transacción sobre todos los repositorios: `with uow: ...; uow.commit()`.

    Al salir del bloque sin commit se descartan los cambios. Los objetos devueltos
    pueden cargar sus relaciones (p. ej. purchase.items) mientras el bloque siga abierto.
    """

    users: UserRepository
    purchases: PurchaseRepository
    attachments: AttachmentRepository
    categories: CategoryRepository

    def __enter__(self) -> Self: ...
    def __exit__(self, *exc) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
